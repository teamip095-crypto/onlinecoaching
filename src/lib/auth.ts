import type { NextAuthOptions } from "next-auth";
import CredentialsProvider from "next-auth/providers/credentials";
import bcrypt from "bcryptjs";
import { db } from "./db";
import {
  checkRateLimit,
  recordFailedLogin,
  clearLoginAttempts,
  persistSession,
} from "./otp";

// Re-export for backward compat with code that imports from auth.ts
export { checkRateLimit, recordFailedLogin, clearLoginAttempts };

export const authOptions: NextAuthOptions = {
  session: { strategy: "jwt", maxAge: 24 * 60 * 60 }, // 1 day
  jwt: { maxAge: 24 * 60 * 60 },
  pages: {
    signIn: "/",
    error: "/",
  },
  providers: [
    CredentialsProvider({
      name: "credentials",
      credentials: {
        email: { label: "Email", type: "email" },
        password: { label: "Password", type: "password" },
      },
      async authorize(credentials, req) {
        if (!credentials?.email || !credentials?.password) return null;
        const email = credentials.email.toLowerCase().trim();
        const rate = await checkRateLimit(`login:${email}`);
        if (!rate.ok) {
          throw new Error(
            `Too many attempts. Try again in ${rate.retryAfter}s`
          );
        }
        const user = await db.user.findUnique({
          where: { email },
        });
        if (!user) {
          await recordFailedLogin(`login:${email}`);
          return null;
        }
        if (user.isBlocked) {
          throw new Error("Account blocked. Contact admin.");
        }
        const ok = await bcrypt.compare(credentials.password, user.passwordHash);
        if (!ok) {
          await recordFailedLogin(`login:${email}`);
          return null;
        }
        await clearLoginAttempts(`login:${email}`);
        // Persist session to DB (single-device enforcement)
        // The actual JWT token is generated by NextAuth — we can't access it here,
        // but the session callback will be invoked next.
        return {
          id: user.id,
          email: user.email,
          name: user.name,
          role: user.role,
          rollNo: user.rollNo ?? "",
        };
      },
    }),
  ],
  callbacks: {
    async jwt({ token, user }) {
      if (user) {
        token.id = user.id;
        token.role = (user as { role?: string }).role ?? "STUDENT";
        token.rollNo = (user as { rollNo?: string }).rollNo ?? "";
      }
      return token;
    },
    async session({ session, token }) {
      if (session.user) {
        (session.user as { id?: string }).id = token.id as string;
        (session.user as { role?: string }).role = token.role as string;
        (session.user as { rollNo?: string }).rollNo = token.rollNo as string;
      }
      return session;
    },
  },
  // No hardcoded fallback — NEXTAUTH_SECRET must be set in environment.
  secret: (() => {
    const s = process.env.NEXTAUTH_SECRET;
    if (!s) {
      throw new Error(
        "NEXTAUTH_SECRET environment variable is not set. Refusing to start with weak security."
      );
    }
    return s;
  })(),
};
